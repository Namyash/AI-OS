// @vitest-environment node
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { ProxyOptions } from 'vite';
import { afterAll, afterEach, beforeAll, describe, expect, it, vi } from 'vitest';
import {
  BACKEND_PATHS,
  BACKEND_URL_VARIABLE,
  backendProxy,
  DEFAULT_BACKEND_URL,
  DEV_TOKEN_FILE_VARIABLE,
  readDevToken,
  resolveBackendOrigin,
} from '../backend-proxy';
import viteConfig from '../vite.config';

/**
 * The dev and preview servers may attach the developer's bearer token to requests for the proxy target, so the target
 * must be the backend and must be on this computer, and the token must come from the file the developer named and
 * go nowhere else. These tests keep those properties from regressing.
 *
 * Runs in the node environment: importing vite.config.ts loads Vite and esbuild, which jsdom's globals break.
 */
const frontendRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const repositoryRoot = join(frontendRoot, '..');

/** Obviously fake; the real token is generated by the backend at each start and never appears in the repository. */
const FAKE_TOKEN = 'fake-dev-token-0123456789-abcdef';

let scratch: string;
let filesWritten = 0;

beforeAll(() => {
  scratch = mkdtempSync(join(tmpdir(), 'pai-backend-proxy-'));
});

afterAll(() => {
  rmSync(scratch, { recursive: true, force: true });
});

/** Writes `contents` to a new file in the scratch directory and returns its absolute path. */
function fileWith(contents: string): string {
  filesWritten += 1;
  const path = join(scratch, `token-${filesWritten}`);
  writeFileSync(path, contents);
  return path;
}

function read(...segments: string[]): string {
  return readFileSync(join(repositoryRoot, ...segments), 'utf8');
}

/** The backend's default address, read from the only file that defines it. */
function backendDefaultOrigin(): string {
  const source = read('backend', 'core', 'config.py');
  const host = /^DEFAULT_HOST\s*=\s*"([^"]+)"/m.exec(source)?.[1];
  const port = /^DEFAULT_PORT\s*=\s*(\d+)/m.exec(source)?.[1];
  if (host === undefined || port === undefined) {
    throw new Error('DEFAULT_HOST or DEFAULT_PORT not found in backend/core/config.py: update this test with it.');
  }
  return `http://${host}:${port}`;
}

describe('default proxy target', () => {
  it('is the address the backend listens on when it has no settings', () => {
    expect(DEFAULT_BACKEND_URL).toBe(backendDefaultOrigin());
    expect(resolveBackendOrigin(undefined)).toBe(backendDefaultOrigin());
  });

  it.each([
    ['frontend/.env.example', () => readFileSync(join(frontendRoot, '.env.example'), 'utf8')],
    ['docs/development/FRONTEND.md', () => read('docs', 'development', 'FRONTEND.md')],
  ])('is the one written in %s', (_name, load) => {
    expect(load()).toContain(DEFAULT_BACKEND_URL);
  });
});

describe('resolveBackendOrigin', () => {
  it.each([undefined, '', '   '])('falls back to the default for %j', (value) => {
    expect(resolveBackendOrigin(value)).toBe(DEFAULT_BACKEND_URL);
  });

  it.each([
    ['http://127.0.0.1:9000', 'http://127.0.0.1:9000'],
    ['http://localhost:9000', 'http://localhost:9000'],
    ['http://[::1]:9000', 'http://[::1]:9000'],
    ['https://127.0.0.1:9443', 'https://127.0.0.1:9443'],
    ['  http://127.0.0.1:9000  ', 'http://127.0.0.1:9000'],
    ['http://127.0.0.1:9000/some/path?x=1', 'http://127.0.0.1:9000'],
  ])('accepts a backend on this computer: %j', (value, origin) => {
    expect(resolveBackendOrigin(value)).toBe(origin);
  });

  it.each([
    ['another host', 'http://backend.internal:8765'],
    ['a private network address', 'http://10.0.0.5:8765'],
    ['the unspecified address', 'http://0.0.0.0:8765'],
    ['a host that only starts with localhost', 'http://localhost.attacker.example'],
    ['a host that only starts with an address', 'http://127.0.0.1.attacker.example'],
    ['a host that only starts with 127.', 'http://127.attacker.example'],
    ['a host that only ends with localhost', 'http://notlocalhost:8765'],
    ['a sub-domain of localhost', 'http://backend.localhost:8765'],
    ['credentials that make a loopback address look like the user name', 'http://127.0.0.1@attacker.example'],
    ['a loopback address in the fragment', 'http://attacker.example#@127.0.0.1'],
    ['a loopback address in the path', 'http://attacker.example/127.0.0.1'],
    ['another scheme', 'ftp://127.0.0.1'],
    ['a file URL', 'file:///etc/passwd'],
    ['a name that is not a URL', 'not a url'],
    ['an address without a scheme', '127.0.0.1:8765'],
  ])('refuses %s', (_name, value) => {
    expect(() => resolveBackendOrigin(value)).toThrow(BACKEND_URL_VARIABLE);
  });

  it('does not repeat a refused value, which may carry credentials', () => {
    let message: string | undefined;
    try {
      resolveBackendOrigin('http://user:hunter2@attacker.example');
    } catch (error) {
      message = error instanceof Error ? error.message : String(error);
    }

    expect(message).toContain(BACKEND_URL_VARIABLE);
    expect(message).not.toMatch(/hunter2|attacker/);
  });
});

describe('backendProxy', () => {
  it('forwards every backend path to the configured backend, and nothing else', () => {
    const proxy = backendProxy({ [BACKEND_URL_VARIABLE]: 'http://127.0.0.1:9000' });

    expect(Object.keys(proxy)).toEqual([...BACKEND_PATHS]);
    for (const options of Object.values(proxy)) {
      expect(options).toMatchObject({ target: 'http://127.0.0.1:9000', changeOrigin: true });
    }
  });

  it('uses the default target when the variable is not set', () => {
    expect(Object.values(backendProxy({}))[0]).toMatchObject({ target: DEFAULT_BACKEND_URL });
  });

  it('refuses a target that is not on this computer', () => {
    expect(() => backendProxy({ [BACKEND_URL_VARIABLE]: 'http://backend.internal:8765' })).toThrow(
      BACKEND_URL_VARIABLE,
    );
  });
});

describe('readDevToken', () => {
  it('returns the token in the file', () => {
    expect(readDevToken(fileWith(FAKE_TOKEN))).toEqual({ token: FAKE_TOKEN });
  });

  it.each([
    ['a trailing newline', `${FAKE_TOKEN}\n`],
    ['a trailing Windows line ending', `${FAKE_TOKEN}\r\n`],
    ['spaces around it', `  ${FAKE_TOKEN}  `],
    ['a byte order mark', `﻿${FAKE_TOKEN}`],
  ])('ignores %s', (_name, contents) => {
    expect(readDevToken(fileWith(contents))).toEqual({ token: FAKE_TOKEN });
  });

  it('reports a file that does not exist as unreadable', () => {
    expect(readDevToken(join(scratch, 'does-not-exist'))).toEqual({ problem: 'unreadable' });
  });

  it('reports a path that is not a file as unreadable', () => {
    const directory = join(scratch, 'a-directory');
    mkdirSync(directory);

    expect(readDevToken(directory)).toEqual({ problem: 'unreadable' });
  });

  it.each([
    ['nothing', ''],
    ['only whitespace', ' \r\n\t\n'],
  ])('reports a file holding %s as empty', (_name, contents) => {
    expect(readDevToken(fileWith(contents))).toEqual({ problem: 'empty' });
  });

  it.each([
    ['more than one line', 'first\nsecond'],
    ['a header-injection attempt', `${FAKE_TOKEN}\r\nX-Injected: 1`],
    ['a space inside', 'two words'],
    ['a control character', 'ab\u0000cd'],
    ['non-ASCII characters', 'café'],
    ['far more than any token', 'a'.repeat(100_000)],
  ])('refuses content with %s, so it can never become part of a header', (_name, contents) => {
    expect(readDevToken(fileWith(contents))).toEqual({ problem: 'malformed' });
  });

  it('never puts the file content in its result when it refuses it', () => {
    const result = readDevToken(fileWith(`${FAKE_TOKEN} with a space`));

    expect(JSON.stringify(result)).not.toContain(FAKE_TOKEN);
  });
});

describe(`backendProxy with ${DEV_TOKEN_FILE_VARIABLE}`, () => {
  type Request = { setHeader(name: string, value: string): void };

  /** What the proxy does to one request on its way to the backend: the headers it sets. */
  function forward(options: ProxyOptions): Map<string, string> {
    const handlers: Array<(request: Request) => void> = [];
    const proxy = { on: (_event: string, handler: (request: Request) => void) => handlers.push(handler) };
    options.configure?.(proxy as unknown as Parameters<NonNullable<ProxyOptions['configure']>>[0], options);

    const headers = new Map<string, string>();
    for (const handler of handlers) {
      handler({ setHeader: (name, value) => headers.set(name, value) });
    }
    return headers;
  }

  function proxyFor(tokenFile: string | undefined, warn: (message: string) => void = () => undefined): ProxyOptions {
    const env: Record<string, string> = { [BACKEND_URL_VARIABLE]: 'http://127.0.0.1:9000' };
    if (tokenFile !== undefined) {
      env[DEV_TOKEN_FILE_VARIABLE] = tokenFile;
    }
    const options = Object.values(backendProxy(env, warn))[0];
    if (!options) {
      throw new Error('backendProxy returned no proxy entries');
    }
    return options;
  }

  it.each([undefined, '', '   '])('adds nothing when the variable is %j', (value) => {
    const options = proxyFor(value);

    expect(options.configure).toBeUndefined();
    expect(forward(options).size).toBe(0);
  });

  it('adds the token from the file as a bearer Authorization header', () => {
    const headers = forward(proxyFor(fileWith(`${FAKE_TOKEN}\n`)));

    expect([...headers]).toEqual([['Authorization', `Bearer ${FAKE_TOKEN}`]]);
  });

  it('applies to every forwarded path', () => {
    const file = fileWith(FAKE_TOKEN);
    const table = backendProxy({ [BACKEND_URL_VARIABLE]: 'http://127.0.0.1:9000', [DEV_TOKEN_FILE_VARIABLE]: file });

    expect(Object.keys(table).length).toBeGreaterThan(0);
    for (const options of Object.values(table)) {
      expect(forward(options).get('Authorization')).toBe(`Bearer ${FAKE_TOKEN}`);
    }
  });

  it('reads the file for every request, so a backend restart needs no dev server restart', () => {
    const file = fileWith('first-token');
    const options = proxyFor(file);
    expect(forward(options).get('Authorization')).toBe('Bearer first-token');

    writeFileSync(file, 'second-token');

    expect(forward(options).get('Authorization')).toBe('Bearer second-token');
  });

  it('keeps neither the token nor the path in the proxy options', () => {
    const file = fileWith(FAKE_TOKEN);

    const serialised = JSON.stringify(proxyFor(file));

    expect(serialised).not.toContain(FAKE_TOKEN);
    expect(serialised).not.toContain(file);
  });

  describe('when the file cannot be used', () => {
    it('forwards the request without credentials and says why, once', () => {
      const file = join(scratch, 'not-written-yet');
      const warnings: string[] = [];
      const options = proxyFor(file, (message) => warnings.push(message));

      expect(forward(options).size).toBe(0);
      expect(forward(options).size).toBe(0);

      expect(warnings).toHaveLength(1);
      expect(warnings[0]).toContain(DEV_TOKEN_FILE_VARIABLE);
      expect(warnings[0]).toContain('cannot be read');
      expect(warnings[0]).not.toContain(file);
    });

    it('starts working as soon as the file appears, and warns again if it breaks again', () => {
      const file = join(scratch, 'appears-later');
      const warnings: string[] = [];
      const options = proxyFor(file, (message) => warnings.push(message));
      expect(forward(options).size).toBe(0);

      writeFileSync(file, FAKE_TOKEN);
      expect(forward(options).get('Authorization')).toBe(`Bearer ${FAKE_TOKEN}`);

      writeFileSync(file, '');
      expect(forward(options).size).toBe(0);

      expect(warnings).toHaveLength(2);
      expect(warnings[1]).toContain('is empty');
    });

    it.each([
      ['an empty file', '', 'is empty'],
      ['a file with only whitespace', '\n\n', 'is empty'],
      ['a file with more than a token', `${FAKE_TOKEN}\r\nX-Injected: 1`, 'single line'],
    ])('sends no header for %s and never repeats its content in the warning', (_name, contents, wording) => {
      const warnings: string[] = [];
      const options = proxyFor(fileWith(contents), (message) => warnings.push(message));

      expect(forward(options).size).toBe(0);

      expect(warnings).toHaveLength(1);
      expect(warnings[0]).toContain(wording);
      expect(warnings[0]).not.toContain(FAKE_TOKEN);
      expect(warnings[0]).not.toContain('X-Injected');
    });
  });

  it('requires an absolute path, like the backend does for its own token file', () => {
    expect(() => proxyFor('relative/pai-token')).toThrow(DEV_TOKEN_FILE_VARIABLE);
  });

  it('refuses to inject for a target that is not on this computer, whatever the token file holds', () => {
    const file = fileWith(FAKE_TOKEN);
    const env = { [BACKEND_URL_VARIABLE]: 'http://backend.internal:8765', [DEV_TOKEN_FILE_VARIABLE]: file };
    let thrown: unknown;
    let table: unknown;

    try {
      table = backendProxy(env);
    } catch (error) {
      thrown = error;
    }

    // No proxy table exists, so there is nothing that could add the header; and the message leaks neither value.
    expect(table).toBeUndefined();
    expect(thrown).toBeInstanceOf(Error);
    const message = (thrown as Error).message;
    expect(message).toContain(BACKEND_URL_VARIABLE);
    expect(message).not.toContain(FAKE_TOKEN);
    expect(message).not.toContain(file);
  });

  it.each([
    ['another host', 'http://backend.internal:8765'],
    ['a look-alike of a loopback name', 'http://localhost.attacker.example'],
    ['a loopback address used as credentials', 'http://127.0.0.1@attacker.example'],
    ['the unspecified address', 'http://0.0.0.0:8765'],
  ])('refuses to inject for %s', (_name, target) => {
    const env = { [BACKEND_URL_VARIABLE]: target, [DEV_TOKEN_FILE_VARIABLE]: fileWith(FAKE_TOKEN) };

    expect(() => backendProxy(env)).toThrow(BACKEND_URL_VARIABLE);
  });
});

describe('vite.config.ts', () => {
  afterEach(() => {
    vi.unstubAllEnvs();
  });

  /** The developer's own shell or frontend/.env must not decide the outcome of these tests. */
  function stubEnv(target: string, tokenFile = ''): void {
    vi.stubEnv(BACKEND_URL_VARIABLE, target);
    vi.stubEnv(DEV_TOKEN_FILE_VARIABLE, tokenFile);
  }

  it('does not look at the proxy settings when building, so a stray variable cannot break `npm run build`', () => {
    stubEnv('http://backend.internal:8765', 'relative/pai-token');

    const config = viteConfig({ command: 'build', mode: 'production' });

    expect(config.server?.proxy).toBeUndefined();
    expect(config.preview?.proxy).toBeUndefined();
  });

  it('refuses to start the dev and preview servers when the target is not on this computer', () => {
    stubEnv('http://backend.internal:8765');

    expect(() => viteConfig({ command: 'serve', mode: 'development' })).toThrow(BACKEND_URL_VARIABLE);
    expect(() => viteConfig({ command: 'serve', mode: 'production', isPreview: true })).toThrow(BACKEND_URL_VARIABLE);
  });

  it('refuses to start the servers when the token file is not an absolute path', () => {
    stubEnv('http://127.0.0.1:9000', 'relative/pai-token');

    expect(() => viteConfig({ command: 'serve', mode: 'development' })).toThrow(DEV_TOKEN_FILE_VARIABLE);
  });

  it('gives the dev and preview servers the same proxy, bound to this computer only', () => {
    stubEnv('http://127.0.0.1:9000');

    const config = viteConfig({ command: 'serve', mode: 'development' });

    expect(config.server?.proxy).toEqual(backendProxy({ [BACKEND_URL_VARIABLE]: 'http://127.0.0.1:9000' }));
    expect(config.preview?.proxy).toBe(config.server?.proxy);
    expect(config.server?.host).toBe('127.0.0.1');
    expect(config.preview?.host).toBe('127.0.0.1');
  });

  it('gives the dev and preview servers the token injection when a token file is named, and not otherwise', () => {
    stubEnv('http://127.0.0.1:9000', fileWith(FAKE_TOKEN));
    const withFile = viteConfig({ command: 'serve', mode: 'development' });
    stubEnv('http://127.0.0.1:9000');
    const without = viteConfig({ command: 'serve', mode: 'development' });

    const entries = (config: ReturnType<typeof viteConfig>) =>
      [config.server, config.preview].flatMap((section) => Object.values(section?.proxy ?? {}));
    expect(entries(withFile)).not.toHaveLength(0);
    for (const options of entries(withFile)) {
      expect(options).toMatchObject({ configure: expect.any(Function) });
    }
    expect(entries(without)).not.toHaveLength(0);
    for (const options of entries(without)) {
      expect(options).not.toHaveProperty('configure');
    }
  });
});

