// @vitest-environment node

import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { createServer as createHttpServer, type IncomingHttpHeaders, type Server } from 'node:http';
import type { AddressInfo } from 'node:net';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer as createViteServer } from 'vite';
import { afterAll, afterEach, beforeAll, describe, expect, it, vi } from 'vitest';
import { BACKEND_URL_VARIABLE, DEV_TOKEN_FILE_VARIABLE } from '../backend-proxy';

/**
 * The real dev server, built from the real vite.config.ts, in front of a stand-in backend: what the backend receives
 * is what proves that the token goes from the file the developer named to the backend, and nowhere else. The unit
 * tests in backend-proxy.test.ts cover the pieces; this covers that they are wired into the servers.
 */
const frontendRoot = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Obviously fake; the real token is generated by the backend at each start and never appears in the repository. */
const FAKE_TOKEN = 'fake-dev-token-0123456789-abcdef';

let scratch: string;
let backend: Server;
/** Headers of every request that reached the stand-in backend, newest last. */
let received: IncomingHttpHeaders[] = [];
/** Closes what each test started, in the order given. */
let closers: Array<() => Promise<void>> = [];
let tokenFilesWritten = 0;
let backendUrl: string;

beforeAll(async () => {
  scratch = mkdtempSync(join(tmpdir(), 'pai-dev-proxy-'));
  backend = createHttpServer((request, response) => {
    received.push(request.headers);
    const authorised = request.headers.authorization === `Bearer ${FAKE_TOKEN}`;
    response.writeHead(authorised ? 200 : 401, { 'Content-Type': 'application/json' });
    response.end(
      JSON.stringify(
        authorised
          ? { status: 'ok', schema_version: 1, version: '0.0.1' }
          : { error: { code: 'unauthorized', message: 'Authentication is required.' } },
      ),
    );
  });
  await new Promise<void>((resolve) => backend.listen(0, '127.0.0.1', resolve));
  backendUrl = `http://127.0.0.1:${(backend.address() as AddressInfo).port}`;
});

afterEach(async () => {
  vi.unstubAllEnvs();
  received = [];
  await Promise.all(closers.map((close) => close()));
  closers = [];
});

afterAll(async () => {
  await new Promise<void>((resolve) => backend.close(() => resolve()));
  rmSync(scratch, { recursive: true, force: true });
});

/**
 * Starts the dev server with the project's own configuration and returns a function that sends it a request. The server
 * runs in middleware mode behind a throw-away HTTP listener: same proxy, no hot-reload socket, and its cache is kept
 * out of node_modules.
 */
async function devServer(tokenFile: string): Promise<(path: string) => Promise<Response>> {
  vi.stubEnv(BACKEND_URL_VARIABLE, backendUrl);
  vi.stubEnv(DEV_TOKEN_FILE_VARIABLE, tokenFile);
  const vite = await createViteServer({
    root: frontendRoot,
    configFile: join(frontendRoot, 'vite.config.ts'),
    logLevel: 'silent',
    appType: 'custom',
    cacheDir: join(scratch, 'vite-cache'),
    server: { middlewareMode: true, hmr: false, watch: null },
    optimizeDeps: { noDiscovery: true, include: [] },
  });
  const front = createHttpServer(vite.middlewares);
  await new Promise<void>((resolve) => front.listen(0, '127.0.0.1', resolve));
  closers.push(
    () => new Promise<void>((resolve) => front.close(() => resolve())),
    () => vite.close(),
  );
  const origin = `http://127.0.0.1:${(front.address() as AddressInfo).port}`;
  return (path) => fetch(`${origin}${path}`);
}

function tokenFileWith(contents: string): string {
  tokenFilesWritten += 1;
  const path = join(scratch, `token-${tokenFilesWritten}`);
  writeFileSync(path, contents);
  return path;
}

describe('dev server proxy with a token file', () => {
  it('signs /health in with the token from the file, and the answer reaches the page without it', async () => {
    const get = await devServer(tokenFileWith(`${FAKE_TOKEN}\n`));

    const reply = await get('/health');

    expect(reply.status).toBe(200);
    expect(await reply.json()).toEqual({ status: 'ok', schema_version: 1, version: '0.0.1' });
    expect(received).toHaveLength(1);
    expect(received[0]?.authorization).toBe(`Bearer ${FAKE_TOKEN}`);
    expect(JSON.stringify([...reply.headers])).not.toContain(FAKE_TOKEN);
  });

  it('picks up a new token written by a restarted backend without restarting the dev server', async () => {
    const file = tokenFileWith('stale-token');
    const get = await devServer(file);
    expect((await get('/health')).status).toBe(401);

    writeFileSync(file, FAKE_TOKEN);

    expect((await get('/health')).status).toBe(200);
    expect(received.map((headers) => headers.authorization)).toEqual(['Bearer stale-token', `Bearer ${FAKE_TOKEN}`]);
  });

  it('still forwards the request, without credentials, when the file is missing, so the page shows the 401', async () => {
    vi.spyOn(console, 'warn').mockImplementation(() => undefined);
    const get = await devServer(join(scratch, 'never-written'));

    const reply = await get('/health');

    expect(reply.status).toBe(401);
    expect(await reply.json()).toEqual({ error: { code: 'unauthorized', message: 'Authentication is required.' } });
    expect(received).toHaveLength(1);
    expect(received[0]).not.toHaveProperty('authorization');
    expect(console.warn).toHaveBeenCalledTimes(1);
  });

  it('adds nothing when no token file is named', async () => {
    const get = await devServer('');

    const reply = await get('/health');

    expect(reply.status).toBe(401);
    expect(received[0]).not.toHaveProperty('authorization');
  });
});
